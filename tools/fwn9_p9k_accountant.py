"""FWN9 P9K independent Decimal accounting of receipt-driven offline fixture.
No market model, no broker, no simulated fills generated by this calculator.
"""
from __future__ import annotations
from decimal import Decimal, localcontext
import json
import sys
from pathlib import Path
from typing import Any


def verify(path: Path) -> dict[str, Any]:
    payload: dict[str, Any] | None = None
    for line in path.read_text().splitlines():
        if line.startswith("P9K_AUDIT="):
            if payload is not None:
                raise ValueError("P9K_DUPLICATE_AUDIT_INPUT")
            value = json.loads(line.removeprefix("P9K_AUDIT="))
            if not isinstance(value, dict):
                raise ValueError("P9K_AUDIT_NOT_OBJECT")
            payload = value
    if payload is None:
        raise ValueError("P9K_MISSING_AUDIT_INPUT")
    if payload["classification"] != "DETERMINISTIC_ENGINEERING_ONLY":
        raise ValueError("P9K_UNSUPPORTED_MARKET_CLAIM")
    if payload["perSideFeeUsd"] != 0.005 or payload["capitalUsd"] != 20000:
        raise ValueError("P9K_CHANGED_CAPITAL_OR_FEE")
    orders = payload["orders"]
    book = payload["book"]
    rows = payload["log"]
    s = payload["snapshot"]
    if set(orders) != {"a", "b"} or len(book["reservations"]) != 2:
        raise ValueError("P9K_UNEXPECTED_ENGINEERING_ORDERS")
    if len(rows) != 8 or len({row["id"] for row in rows}) != len(rows):
        raise ValueError("P9K_EVENT_ID_OR_COUNT")
    if any(row["knownAt"] < row["at"] for row in rows):
        raise ValueError("P9K_NONCAUSAL_LEDGER_EVENT")
    if any(rows[i]["knownAt"] < rows[i - 1]["knownAt"]
           for i in range(1, len(rows))):
        raise ValueError("P9K_RECEIPT_REGRESSION")

    with localcontext() as context:
        context.prec = 60
        dec = lambda v: Decimal(str(v))
        fee = dec(payload["perSideFeeUsd"])
        capital = dec(payload["capitalUsd"])
        gross_costs = sum((dec(o["entrySpendUsd"]) for o in orders.values()), Decimal(0))
        proceeds = sum((dec(o["exitProceedsUsd"]) for o in orders.values()), Decimal(0))
        actual_fees = sum((dec(o["totalEntryFeesUsd"]) +
                           dec(o["totalExitFeesUsd"]) for o in orders.values()), Decimal(0))
        expected_fees = fee * Decimal(8)
        assert actual_fees == expected_fees
        daily = dec(s["externalCostsUsd"])
        cash = capital - daily - gross_costs + proceeds - actual_fees
        if abs(cash - dec(s["physicalCashUsd"])) >= Decimal("1e-7"):
            raise ValueError("P9K_PHYSICAL_CASH_MISMATCH")
        if abs(cash - dec(s["equityUsd"])) >= Decimal("1e-7"):
            raise ValueError("P9K_TERMINAL_EQUITY_MISMATCH")
        if s["positions"] != 0 or s["reservationCount"] != 0:
            raise ValueError("P9K_PHANTOM_TERMINAL_POSITION")
        if s["feesPaidUsd"] != float(actual_fees):
            raise ValueError("P9K_FEES_RECEIPTS_MISMATCH")
        if s["pendingCashUsd"] != 0:
            raise ValueError("P9K_GHOST_PENDING_CASH")
        for r in book["reservations"]:
            terminal = r["observations"][-1]
            if terminal["kind"] not in {"CLOSED", "NO_FILL"}:
                raise ValueError("P9K_RESERVATION_NOT_TERMINATED")
            if terminal["remainingQuantity"] != 0 or terminal["pendingQuantity"] != 0:
                raise ValueError("P9K_RESIDUAL_RESERVATION")
        if s["n9sEligible"] is not False or s["allNativeM9PathsProven"] is not False:
            raise ValueError("P9K_FALSE_PROMOTION")
        return {"status": "PASS_DECIMAL_60", "orders": len(orders),
                "receipt_events": len(rows),
                "physical_cash_usd": str(cash),
                "net_after_costs_usd": str(cash-capital),
                "fees_usd": str(actual_fees),
                "calendar_costs_usd": str(daily),
                "m9_native_population_verified": False,
                "real_trades": 0}


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("expected one P9K audit log")
    print(json.dumps(verify(Path(sys.argv[1])), indent=2, sort_keys=True))
