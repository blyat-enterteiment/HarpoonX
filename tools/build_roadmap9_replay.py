#!/usr/bin/env python3
"""Build the additive research fork from the immutable measured replay.

Six explicit substitutions preserve the existing ledger and its sealed source.
The generated file is committed and checked against this builder in tests.
"""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA = "84594c176040c058506e9ba1323ae11901897a5023621c12c0e00c484c5f354c"


def build() -> str:
    source = (ROOT / "runtime30/ultimate_replay_research.js").read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise ValueError("ROADMAP_REPLAY_BASE_CHANGED")
    text = source.decode()
    replacements = [
        (
            "const target72h = signal.at + 72 * 3600000;",
            (
                "const roadmapHours = signal.metadata?.roadmapHorizonHours ?? 72;\n"
                '    (0, ultimate_contracts_1.need)([24,48,72].includes(roadmapHours), "ROADMAP_HORIZON");\n'
                "    const target72h = signal.at + roadmapHours * 3600000;"
            ),
        ),
        (
            '(0, policy_1.deadlineFor)("equity", signal.at, 72, data.sessions);',
            '(0, policy_1.deadlineFor)("equity", signal.at, roadmapHours, data.sessions);',
        ),
        (
            "const marks = [], tpDone = [false, false];",
            "const marks = [], tpDone = [false, false];\n    let roadmapReduced = false;",
        ),
        (
            "        const researchReason = signal.metadata?.researchExit",
            (
                '        const roadmapAction = require("./roadmap9_exit.js").exitAction(\n'
                "            signal, b.t, remaining, roadmapReduced, options?.forecastDecisions);\n"
                "        if (roadmapAction) {\n"
                "            close(roadmapAction.quantity, b.o, b.t, roadmapAction.reason);\n"
                "            roadmapReduced = true;\n"
                "            if (!remaining) { marks.push({at:b.t,pnl:realized}); break; }\n"
                "        }\n"
                "        const researchReason = signal.metadata?.researchExit"
            ),
        ),
        (
            (
                "const externalCostAt = (at) => externalCostIsModeled\n"
                "        ? sessions.reduce((n, session) => n + (session.open <= at ? options.externalCostPerSessionUsd : 0), 0) : 0;"
            ),
            (
                "const calendarCost = options?.calendarCostPerDayUsd;\n"
                '    (0, ultimate_contracts_1.need)(calendarCost === undefined || (Number.isFinite(calendarCost) && calendarCost >= 0), "CALENDAR_COST");\n'
                "    const externalCostAt = (at) => calendarCost !== undefined\n"
                "        ? (at < sessions[0].open ? 0 : (Math.floor(at / 86400000) - Math.floor(sessions[0].open / 86400000) + 1) * calendarCost)\n"
                "        : externalCostIsModeled\n"
                "        ? sessions.reduce((n, session) => n + (session.open <= at ? options.externalCostPerSessionUsd : 0), 0) : 0;"
            ),
        ),
        (
            "{ cashDividends: options.cashDividends === true });",
            "{ cashDividends: options.cashDividends === true, forecastDecisions: options.forecastDecisions });",
        ),
    ]
    for old, new in replacements:
        if text.count(old) != 1:
            raise ValueError("REPLAY_EXTENSION_ANCHOR_MISMATCH:" + old[:60])
        text = text.replace(old, new)
    return (
        "// Generated by tools/build_roadmap9_replay.py; immutable baseline preserved.\n"
        "// Offline research: causal clock horizons, value exits and calendar overhead.\n"
        + text
    )


if __name__ == "__main__":
    (ROOT / "runtime30/ultimate_replay_roadmap9.js").write_text(build())
